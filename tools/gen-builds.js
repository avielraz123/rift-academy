// Generates js/data/builds.js (builds + tier lists) from patch research JSON files.
// Usage: node tools/gen-builds.js research/*.json
// Each research file:
//   { patch, role?: "mid", tierList?: [{id, tier, note}],
//     champions: [{ id, role?, tier, winRate, summoners, runes, altKeystone, skillMax, firstThree,
//                   starter, core, boots, situational, patchNote }] }
// A champion's role comes from its own "role" field, else the file's "role", else the file name (research-mid.json -> mid).
// Tier lists are read from files whose role is mid or bot.
const fs = require("fs");
const path = require("path");

const files = process.argv.slice(2);
if (!files.length) { console.error("usage: node tools/gen-builds.js <research json files>"); process.exit(1); }
const ROLES = ["top", "jungle", "mid", "bot", "support"];
const out = { builds: {}, tierList: { mid: [], bot: [] } };
let patch = "";

function shortWinRate(s) {
  if (!s) return "";
  const m = String(s).match(/(\d+(?:\.\d+)?)%\s*\(([^,)]+)/);
  return m ? Number(m[1]).toFixed(1) + "% (" + m[2].trim() + ", Emerald+)" : String(s);
}
function clean(s) { return String(s || "").replace(/\s*\(estimate\)/gi, "").trim(); }

for (const file of files) {
  const r = JSON.parse(fs.readFileSync(file, "utf8"));
  patch = r.patch || patch;
  const fileRole = r.role || ROLES.find(x => path.basename(file).includes(x));
  if ((fileRole === "mid" || fileRole === "bot") && r.tierList && r.tierList.length) {
    out.tierList[fileRole] = r.tierList.map(t => ({ id: t.id, tier: String(t.tier).charAt(0), note: clean(t.note) }));
  }
  for (const c of r.champions || []) {
    const role = c.role || fileRole;
    if (!ROLES.includes(role)) { console.error("no role for", c.id, "in", file); process.exitCode = 1; continue; }
    out.builds[c.id + ":" + role] = {
      tier: String(c.tier || "").charAt(0),
      winRate: shortWinRate(c.winRate),
      summoners: c.summoners,
      runes: c.runes,
      altKeystone: c.altKeystone && c.altKeystone.keystone ? { keystone: c.altKeystone.keystone, when: clean(c.altKeystone.when) } : null,
      skillMax: c.skillMax,
      firstThree: c.firstThree,
      starter: c.starter,
      core: c.core,
      boots: c.boots,
      situational: (c.situational || []).map(s => ({ item: s.item, when: clean(s.when) })),
      note: clean(c.patchNote)
    };
  }
}

const sorted = {};
Object.keys(out.builds).sort().forEach(k => { sorted[k] = out.builds[k]; });
const js = "// Generated by tools/gen-builds.js from patch " + patch + " research (research/*.json). Re-generate each patch; don't edit by hand.\n" +
  "window.RA = window.RA || {};\n" +
  "RA.builds = " + JSON.stringify(sorted, null, 1) + ";\n" +
  "RA.patch = RA.patch || {};\n" +
  "RA.patch.tierList = " + JSON.stringify(out.tierList, null, 1) + ";\n" +
  "RA.patch.tierListNote = " + JSON.stringify("Based on patch " + patch + " Emerald+ ranked data from op.gg and lolalytics.") + ";\n" +
  "RA.patch.sources = " + JSON.stringify([
    { name: "op.gg", url: "https://op.gg/lol/champions" },
    { name: "lolalytics", url: "https://lolalytics.com/lol/tierlist/" },
    { name: "Patch " + patch + " notes", url: "https://www.leagueoflegends.com/en-us/news/game-updates/league-of-legends-patch-" + patch.replace(".", "-") + "-notes" }
  ]) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "js/data/builds.js"), js);
console.log("wrote builds.js:", Object.keys(sorted).length, "builds");
