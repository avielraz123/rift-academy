// Generates js/data/builds.js from patch research JSON files.
// Usage: node tools/gen-builds.js <research-mid.json> <research-bot.json>
// Each research file: { patch, tierList: [{id, tier, note}], champions: [{id, tier, winRate, summoners, runes, altKeystone,
//   skillMax, firstThree, starter, core, boots, situational, patchNote}] }  (see docs/content-format.md)
const fs = require("fs");
const path = require("path");

const [midFile, botFile] = process.argv.slice(2);
if (!midFile || !botFile) { console.error("usage: node tools/gen-builds.js <mid.json> <bot.json>"); process.exit(1); }
const out = { builds: {}, tierList: { mid: [], bot: [] } };
let patch = "";

function shortWinRate(s) {
  if (!s) return "";
  const m = String(s).match(/(\d+(?:\.\d+)?)%\s*\(([^,)]+)/);
  return m ? Number(m[1]).toFixed(1) + "% (" + m[2].trim() + ", Emerald+)" : String(s);
}
function clean(s) { return String(s || "").replace(/\s*\(estimate\)/gi, "").trim(); }

for (const [role, file] of [["mid", midFile], ["bot", botFile]]) {
  const r = JSON.parse(fs.readFileSync(file, "utf8"));
  patch = r.patch || patch;
  out.tierList[role] = (r.tierList || []).map(t => ({ id: t.id, tier: String(t.tier).charAt(0), note: clean(t.note) }));
  for (const c of r.champions || []) {
    out.builds[c.id + ":" + role] = {
      tier: String(c.tier || "").charAt(0),
      winRate: shortWinRate(c.winRate),
      summoners: c.summoners,
      runes: c.runes,
      altKeystone: c.altKeystone && c.altKeystone.keystone ? { keystone: c.altKeystone.keystone, when: clean(c.altKeystone.when) } : null,
      skillMax: c.skillMax,
      firstThree: c.firstThree,
      starter: c.starter,
      core: c.core,
      boots: c.boots,
      situational: (c.situational || []).map(s => ({ item: s.item, when: clean(s.when) })),
      note: clean(c.patchNote)
    };
  }
}

const js = "// Generated by tools/gen-builds.js from patch " + patch + " research. Re-generate each patch; don't edit by hand.\n" +
  "window.RA = window.RA || {};\n" +
  "RA.builds = " + JSON.stringify(out.builds, null, 1) + ";\n" +
  "RA.patch = RA.patch || {};\n" +
  "RA.patch.tierList = " + JSON.stringify(out.tierList, null, 1) + ";\n" +
  "RA.patch.tierListNote = " + JSON.stringify("Based on patch " + patch + " Emerald+ ranked data from op.gg and lolalytics.") + ";\n" +
  "RA.patch.sources = " + JSON.stringify([
    { name: "op.gg", url: "https://op.gg/lol/champions" },
    { name: "lolalytics", url: "https://lolalytics.com/lol/tierlist/" },
    { name: "Patch " + patch + " notes", url: "https://www.leagueoflegends.com/en-us/news/game-updates/league-of-legends-patch-" + patch.replace(".", "-") + "-notes" }
  ]) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "js/data/builds.js"), js);
console.log("wrote builds.js:", Object.keys(out.builds).length, "builds");
