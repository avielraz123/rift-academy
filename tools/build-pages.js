// Pre-renders every page of the site into a real HTML file, so search engines can index each page and
// link previews (Discord, WhatsApp, X…) show the right title, description and image.
//   guide/wave-management  ->  guide/wave-management/index.html
// Also writes 404.html (GitHub Pages serves it for unknown paths; the app then renders the page itself),
// sitemap.xml and updates index.html (the home page). Run after any content change:
//   npm install   (once; installs jsdom)
//   node tools/build-pages.js
// The site still works without this step: index.html alone renders every page from #/route links.
"use strict";
const fs = require("fs");
const path = require("path");
const { JSDOM, VirtualConsole } = require("jsdom");

const SITE = "https://avielraz123.github.io/rift-academy/";
const SITE_PATH = new URL(SITE).pathname; // "/rift-academy/"
const ROOT = path.join(__dirname, "..");
const DEFAULT_IMAGE = SITE + "og.png";

const template = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
const scripts = [...template.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
if (!scripts.length) throw new Error("no <script src> tags found in index.html");

const errors = [];
const vc = new VirtualConsole();
vc.on("jsdomError", (e) => { if (!/Not implemented/.test(e.message)) errors.push(e.message); });
vc.on("error", (...a) => errors.push(a.join(" ")));

const dom = new JSDOM(template, { url: SITE, runScripts: "outside-only", pretendToBeVisual: true, virtualConsole: vc });
const { window } = dom;
window.RA_ROOT = SITE;
window.eval("Math.random = function () { return 0; };"); // same output every run (e.g. the home page hero)
window.scrollTo = function () {};
for (const src of scripts) window.eval(fs.readFileSync(path.join(ROOT, src), "utf8") + "\n//# sourceURL=" + src);
const RA = window.RA;
RA.start();

// Every page we publish. Query-string variants (filters, tabs) share their page's file.
const routes = ["", "guides", "roles", "champions", "tierlist", "tools", "glossary", "search", "path"];
if (RA.patchChanges) routes.push("patch");
RA.guides.forEach((g) => routes.push("guide/" + g.id));
RA.roles.forEach((r) => routes.push("role/" + r.id));
RA.champs.forEach((c) => c.roles.forEach((role, i) => routes.push("champion/" + c.id + (i ? "/" + role : ""))));
Object.keys(RA.tools).forEach((k) => routes.push("tools/" + k));

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function seoBlock(url, meta, noindex) {
  const img = meta.image || DEFAULT_IMAGE;
  return [
    "<!-- seo: generated by tools/build-pages.js -->",
    noindex ? '<meta name="robots" content="noindex">' : '<link rel="canonical" href="' + esc(url) + '">',
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="Rift Academy">',
    '<meta property="og:title" content="' + esc(meta.title) + '">',
    '<meta property="og:description" content="' + esc(meta.desc) + '">',
    '<meta property="og:url" content="' + esc(url) + '">',
    '<meta property="og:image" content="' + esc(img) + '">',
    '<meta name="twitter:card" content="summary_large_image">',
    "<!-- /seo -->"
  ].join("\n  ");
}

// Render one route and return the full HTML document.
function renderPage(route, opts) {
  errors.length = 0;
  window.history.replaceState(null, "", SITE + (route ? route + "/" : ""));
  RA.render();
  if (errors.length) throw new Error("errors while rendering /" + route + ": " + errors.join(" | "));
  const doc = window.document;
  const text = doc.getElementById("app").textContent.trim();
  if (!opts.allowShort && text.length < 200) throw new Error("/" + route + " rendered almost nothing (" + text.length + " chars)");
  if (/\{\{[^}]*\}\}/.test(doc.getElementById("app").innerHTML)) throw new Error("/" + route + " has an unexpanded {{token}}");
  let html = dom.serialize();
  const url = SITE + (route ? route + "/" : "");
  html = html.replace(/\s*<!-- seo: generated[\s\S]*?<!-- \/seo -->/, "");
  html = html.replace(/(<meta name="description"[^>]*>)/, "$1\n  " + seoBlock(url, RA.meta, opts.noindex));
  // Pages below the root load css/js from the site root.
  if (opts.absoluteAssets) html = html.replace(/(href|src)="(css|js)\//g, '$1="' + SITE_PATH + "$2/");
  return html;
}

function write(rel, html) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html.replace(/\r\n/g, "\n"));
}

// Remove pages from a previous run whose route no longer exists (e.g. a renamed guide).
const sections = ["guide", "role", "champion", "tools", "guides", "roles", "champions", "tierlist", "glossary", "search", "path", "patch"];
const keep = new Set(routes.map((r) => path.join(ROOT, r, "index.html")));
for (const s of sections) {
  const dir = path.join(ROOT, s);
  if (!fs.existsSync(dir)) continue;
  (function walk(d) {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else if (f === "index.html" && !keep.has(p)) fs.unlinkSync(p);
    }
    if (d !== dir && !fs.readdirSync(d).length) fs.rmdirSync(d);
  })(dir);
}

let count = 0;
for (const route of routes) {
  const html = renderPage(route, { absoluteAssets: route !== "", allowShort: route === "search" });
  write(route ? route + "/index.html" : "index.html", html);
  count++;
}
// 404 page: real asset paths from the site root, not indexed.
write("404.html", renderPage("this-page-does-not-exist", { absoluteAssets: true, noindex: true, allowShort: true }));

const sitemap = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  routes.filter((r) => r !== "search").map((r) => "  <url><loc>" + SITE + (r ? r + "/" : "") + "</loc></url>").join("\n") + "\n</urlset>\n";
write("sitemap.xml", sitemap);
if (!fs.existsSync(path.join(ROOT, ".nojekyll"))) write(".nojekyll", "");
window.close();
console.log("Pre-rendered " + count + " pages + 404.html, sitemap.xml (" + (routes.length - 1) + " URLs).");
